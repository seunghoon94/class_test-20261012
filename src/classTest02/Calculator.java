package classTest02;

public class Calculator {
	
	public int add(int a, int b) { //두 수의 합 반환
		return (a+b);
	}
	public int subtrack(int a, int b) { //두 수의 차 반환
		return (a-b);
	}
	public int multiply(int a, int b) { //두 수의 곱 반환
		return (a*b);
	}
	public double divide(int a, int b) { //두 수의 나눗셈 결과를 double로 반환
		return ((double)a/b);
	}

}
